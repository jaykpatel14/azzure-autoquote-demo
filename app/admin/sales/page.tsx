import Link from "next/link";
import { redirect } from "next/navigation";
import InternalAdminShell from "@/components/internal-admin-shell";
import { getInternalAdminContext } from "@/lib/internal-admin";
import { getInternalAdminNav } from "@/lib/internal-admin-nav";
import { AdminSalesImpersonate } from "@/components/admin-sales-impersonate";
import { getAdminSalesQuotes } from "@/src/services/admin-sales";

export const dynamic = "force-dynamic";

function formatCurrency(value: number | any) {
  if (typeof value !== "number") return "$0.00";
  return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(value);
}

export default async function AdminSalesDashboard() {
  const context = await getInternalAdminContext();
  if (!context || context.user.adminRole !== "SALESMAN") {
    redirect("/admin");
  }

  const { quotes, companies } = await getAdminSalesQuotes();

  return (
    <InternalAdminShell
      title="Sales Dashboard"
      description="View recent quotes across all tenants. Displaying Making Price and Tier Pricing only."
      navItems={getInternalAdminNav("/admin/sales")}
      adminName={context.user.name || context.user.email}
      actions={<AdminSalesImpersonate companies={companies} />}
    >
      <section className="card">
        <div className="sectionHeader">
          <div>
            <h2>Recent AI Quotes</h2>
            <p className="muted small">All quotes generated by tenants. Prices shown are wholesale making costs.</p>
          </div>
        </div>
        <div className="tableShell">
          <table className="dataTable">
            <thead>
              <tr>
                <th style={{ width: 120 }}>Quote #</th>
                <th>Tenant</th>
                <th>Item / Metal</th>
                <th>Status</th>
                <th style={{ textAlign: "right" }}>Making Price</th>
                <th style={{ width: 120, textAlign: "right" }}>Date</th>
              </tr>
            </thead>
            <tbody>
              {quotes.length === 0 ? (
                <tr>
                  <td colSpan={6} style={{ textAlign: "center", padding: 32 }} className="muted">No quotes found.</td>
                </tr>
              ) : (
                quotes.map((quote) => (
                  <tr key={quote.id}>
                    <td>
                      <Link href={`/admin/quotes/${quote.id}`} style={{ fontWeight: 600 }}>
                        {quote.quoteNumber}
                      </Link>
                    </td>
                    <td>{quote.company.name}</td>
                    <td>
                      <span style={{ display: "block" }}>{quote.customerName || "Unnamed Quote"}</span>
                      <span className="muted small">{quote.metalType}</span>
                    </td>
                    <td>
                      <span className="badge" style={{ background: quote.pdfStoredAt ? "rgba(16, 185, 129, 0.12)" : "rgba(245, 158, 11, 0.12)", color: quote.pdfStoredAt ? "#10b981" : "#f59e0b" }}>
                        {quote.pdfStoredAt ? "FINALIZED" : "DRAFT"}
                      </span>
                    </td>
                    <td style={{ textAlign: "right", fontFamily: "var(--font-mono)", fontWeight: 600 }}>
                      {formatCurrency((quote.estimatedPrice as any)?.makingCost ?? 0)}
                    </td>
                    <td style={{ textAlign: "right", color: "var(--color-on-surface-variant)", fontSize: 13 }}>
                      {quote.createdAt.toLocaleDateString()}
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </section>
    </InternalAdminShell>
  );
}
